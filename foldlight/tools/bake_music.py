def hz(note: int) -> float:
    return 440 * 2 ** ((note - 69) / 12)


def smoothstep(value: np.ndarray) -> np.ndarray:
    u = np.clip(value, 0, 1)
    return u * u * (3 - 2 * u)


def tone(note: int, seconds: float, instrument: str) -> np.ndarray:
    """Soft additive physical-style voices; no discontinuous oscillators."""
    t = np.arange(max(2, round(seconds * RATE)), dtype=np.float64) / RATE
    phase = TWOPI * hz(note) * t
    attack, release = .012, min(.14, seconds * .3)
    if instrument == "felt":
        signal = (np.sin(phase) * np.exp(-t * 1.45) + .29 * np.sin(phase * 2.001) * np.exp(-t * 3)
                  + .10 * np.sin(phase * 3.002) * np.exp(-t * 6.5))
    elif instrument == "pluck":
        signal = (np.sin(phase) * np.exp(-t * 2.6) + .38 * np.sin(phase * 2) * np.exp(-t * 5.5)
                  + .13 * np.sin(phase * 3) * np.exp(-t * 9))
        attack = .009
    elif instrument == "glass":
        signal = (np.sin(phase) * np.exp(-t * .95) + .18 * np.sin(phase * 2.003) * np.exp(-t * 2.6)
                  + .055 * np.sin(phase * 3.98) * np.exp(-t * 5))
        attack = .045
    elif instrument == "marimba":
        signal = np.sin(phase) * np.exp(-t * 5) + .17 * np.sin(phase * 3.997) * np.exp(-t * 17)
        attack = .009
    elif instrument == "reed":
        vibrato = .035 * np.sin(TWOPI * 4.7 * t) * smoothstep(t / .45)
        signal = np.sin(phase + vibrato) + .15 * np.sin(phase * 2 + vibrato) + .035 * np.sin(phase * 3)
        signal *= .8 + .2 * np.sin(np.pi * t / seconds)
        attack, release = .15, min(.28, seconds * .35)
    elif instrument == "bow":
        vibrato = .025 * np.sin(TWOPI * 4.3 * t)
        signal = np.sin(phase + vibrato) + .30 * np.sin(phase * 2) + .13 * np.sin(phase * 3) + .045 * np.sin(phase * 4)
        signal *= np.exp(-t * .7)
        attack, release = .055, min(.20, seconds * .35)
    elif instrument == "pad":
        signal = (np.sin(phase) + .25 * np.sin(phase * 1.0018 + .2) + .12 * np.sin(phase * 2)) / 1.37
        attack, release = .65, min(.8, seconds * .35)
    elif instrument == "swell":
        signal = np.sin(phase) + .18 * np.sin(phase * 2)
        attack, release = seconds * .6, seconds * .35
    elif instrument == "bass":
        signal = np.sin(phase) + .18 * np.sin(phase * 2)
        signal *= np.exp(-t * .8)
        attack, release = .025, min(.18, seconds * .35)
    else:
        raise ValueError(instrument)
    return signal * smoothstep(t / attack) * smoothstep((seconds - 1 / RATE - t) / release)


def percussion(kind: str) -> np.ndarray:
    seconds = {"kick": .30, "frame": .23, "brush": .10, "tom": .32}[kind]
    t = np.arange(round(seconds * RATE)) / RATE
    if kind == "kick":
        phase = TWOPI * (47 * t + 27 * .028 * (1 - np.exp(-t / .028)))
        result = np.sin(phase) * np.exp(-t * 14)
    elif kind in ("frame", "tom"):
        f = 156 if kind == "frame" else 108
        result = sum(gain * np.sin(TWOPI * f * ratio * t) * np.exp(-t * decay)
                     for ratio, gain, decay in ((1, .70, 16), (1.59, .20, 24), (2.13, .10, 35)))
    else:
        # A brief paper brush made of partials, never a continuous noise bed.
        result = sum(np.sin(TWOPI * f * t + k * .73) / 8
                     for k, f in enumerate((720, 911, 1127, 1411, 1687, 1987, 2333, 2707)))
        result *= np.exp(-t * 46)
    return result * smoothstep(t / .006) * smoothstep((seconds - 1 / RATE - t) / .025)


class Score:
    def __init__(self):
        self.stems = {name: np.zeros((FRAMES, 2), dtype=np.float64) for name in ("base", "energy")}
        self.events: Counter[str] = Counter()

    def add(self, stem: str, mono: np.ndarray, beat: float, gain: float, pan: float = 0) -> None:
        start = round(beat * BEAT_DURATION * RATE) % FRAMES
        stereo = mono[:, None] * np.array([np.sqrt((1 - pan) / 2), np.sqrt((1 + pan) / 2)]) * gain
        end = min(FRAMES, start + len(stereo))
        self.stems[stem][start:end] += stereo[:end - start]
        if start + len(stereo) > FRAMES:
            self.stems[stem][:len(stereo) - (end - start)] += stereo[end - start:]

    def note(self, stem: str, note: int, beat: float, length: float, gain: float, instrument: str, pan: float = 0) -> None:
        self.add(stem, tone(note, length * BEAT_DURATION, instrument), beat, gain, pan)
        self.events[f"{stem}:{instrument}"] += 1

    def drum(self, kind: str, beat: float, gain: float, pan: float = 0) -> None:
        self.add("energy", percussion(kind), beat, gain, pan)
        self.events[f"energy:{kind}"] += 1


def compose(cue: Cue) -> tuple[dict[str, np.ndarray], dict[str, int]]:
    score = Score()
    for phrase, chord in enumerate(cue.harmony):
        origin, sparse, rise = phrase * 8, phrase == 6, phrase in (4, 5)
        for voice, note in enumerate(chord[1:]):
            score.note("base", note, origin - .30, 8.7, (.027 if cue.key != "boss" else .019) * (.82 if sparse else 1),
                       "pad", (-.40, .12, .40)[voice])
        score.note("base", chord[0], origin + .08, 6.8, .060 if cue.key == "eclipse" else .040, "bass")
        for index, (beat, note, length) in enumerate(cue.melody[phrase]):
            gain = {"harbor": .094, "reef": .105, "archive": .092, "eclipse": .072, "boss": .079}[cue.key]
            score.note("base", note, origin + beat, length, gain * (1 - .055 * (index % 3)), cue.instrument, -.14)

        if cue.key == "harbor":
            for j, beat in enumerate((0, 2.5, 4, 6.5) if not sparse else (0, 4)):
                score.note("base", chord[1 + j % 3], origin + beat, 1.7, .040, "felt", .27)
            for j, beat in enumerate((1.5, 3.5, 5.5, 7) if not sparse else (3.5,)):
                score.note("energy", chord[1 + (j + 1) % 3] + 12, origin + beat, 1.05, .048, "pluck", .32)
            for beat in (() if sparse else (0, 4)):
                score.drum("kick", origin + beat, .055)
            if not sparse:
                score.drum("brush", origin + 3, .027, -.3)
                score.drum("brush", origin + 7, .025, .3)
        elif cue.key == "reef":
            pattern = (0, .75, 2, 3.5, 4, 5.25, 6.5, 7.25)
            for j, beat in enumerate(pattern if not sparse else (0, 3.5, 6.5)):
                note = chord[1 + (0, 2, 1, 2, 0, 1, 2, 1)[j] % 3]
                score.note("base", note + (12 if rise and j % 3 == 0 else 0), origin + beat, .9, .050, "marimba", .35)
            for j, beat in enumerate((.5, 1.5, 2.5, 3.5, 4.5, 5.5, 6.5, 7.5) if not sparse else (2.5, 6.5)):
                score.note("energy", chord[1 + (j + 1) % 3] + (12 if rise else 0), origin + beat, .64, .045, "pluck", -.30)
            for beat in (() if sparse else (0, 2.5, 4, 6.5)):
                score.drum("kick", origin + beat, .075)
            for beat in (() if sparse else (2, 6)):
                score.drum("frame", origin + beat, .045, .2)
            for beat in (() if sparse else (.75, 1.75, 3.75, 4.75, 5.75, 7.75)):
                score.drum("brush", origin + beat, .022, -.35 if beat < 4 else .35)
        elif cue.key == "archive":
            for j, beat in enumerate((2, 6) if not sparse else (4,)):
                score.note("base", chord[2 + j % 2] - 12, origin + beat, 1.8, .052, "felt", .3)
            for j, beat in enumerate((1.75, 4.75, 7) if not sparse else (5.25,)):
                score.note("energy", chord[1 + j % 3] + 12, origin + beat, 1.6, .054, "glass", .42)
            if phrase in (1, 3, 5, 7):
                score.note("base", chord[2] + 12, origin + 5.5, 2, .030, "swell", -.45)
            for beat in (() if sparse else (0, 3, 4.5)):
                score.drum("tom", origin + beat, .052)
            for beat in (() if sparse else (2, 6)):
                score.drum("brush", origin + beat, .030, .35)
        elif cue.key == "eclipse":
            for j, beat in enumerate((1, 3.5, 5, 7) if not sparse else (2, 6)):
                score.note("base", chord[1 + j % 3], origin + beat, 1.7, .048, "felt", .35)
            for j, beat in enumerate((0, 1.5, 3, 4, 5.5, 7) if not sparse else (1.5, 5.5)):
                score.note("energy", chord[1 + j % 3] + (12 if rise else 0), origin + beat, .9, .050, "pluck", .25)
            if rise:
                score.note("energy", chord[2] + 12, origin + 1, 4.5, .024, "reed", -.35)
            for beat in (() if sparse else (0, 4)):
                score.drum("kick", origin + beat, .105)
            for beat in (() if sparse else (2.5, 6.5)):
                score.drum("tom", origin + beat, .050, .2)
            if phrase in (1, 3, 5, 7):
                score.drum("frame", origin + 7.25, .040, -.3)
        elif cue.key == "boss":
            for j, beat in enumerate((0, 1.5, 3, 4, 5.5, 7) if not sparse else (0, 4)):
                score.note("base", chord[1 + j % 3], origin + beat, .6, .062, "bow", .25)
                score.note("energy", chord[0] + (12 if j % 3 == 1 else 0), origin + beat, .55, .060, "bass", -.15)
            for j, beat in enumerate((.5, 1, 2, 2.5, 3.5, 4.5, 5, 6, 6.5, 7.5) if not sparse else (3.5, 7.5)):
                score.note("energy", chord[1 + j % 3] + (12 if rise else 0), origin + beat, .45, .048, "pluck", -.30)
            for beat in (() if sparse else (0, 1.5, 3, 4, 5.5, 7)):
                score.drum("kick", origin + beat, .102 if beat in (0, 4) else .067)
            for beat in (() if sparse else (2, 6)):
                score.drum("frame", origin + beat, .065, .2)
            for beat in (() if sparse else (.5, 1.5, 2.5, 3.5, 4.5, 5.5, 6.5, 7.5)):
                score.drum("brush", origin + beat, .021, -.35 if beat < 4 else .35)
            if phrase in (3, 5, 7):
                score.drum("tom", origin + 7.25, .056, -.25)
                score.drum("tom", origin + 7.75, .043, .25)
        # Answers occupy melody gaps rather than unison duplication.
        if phrase in (1, 3, 5, 7):
            answer = cue.melody[phrase][-1][1] - 12
            score.note("energy", answer, origin + 6, 1.45, .035, "reed" if cue.key != "archive" else "glass", .4)

    wet = .19 if cue.key == "archive" else .12
    for name, data in score.stems.items():
        dry = data.copy()
        for delay, gain in ((.183, wet), (.327, wet * .70), (.519, wet * .42)):
            data += np.roll(dry[:, ::-1], round(delay * RATE), axis=0) * gain
        spectrum = np.fft.rfft(data, axis=0)
        frequencies = np.fft.rfftfreq(FRAMES, 1 / RATE)
        high_cut = 1 - smoothstep((frequencies - 4300) / 1700)
        low_cut = smoothstep(frequencies / 32)
        spectrum *= (high_cut * low_cut)[:, None]
        score.stems[name] = np.fft.irfft(spectrum, n=FRAMES, axis=0)
    # Shared gain preserves base/energy balance; any blend in [0,1] remains safe.
    base, energy = score.stems.values()
    worst_case = max(np.abs(base).max(), np.abs(energy).max(), np.abs(base + energy).max())
    master_gain = min(.94, .295 / worst_case)
    edge = np.arange(FRAMES) / RATE
    fade = smoothstep(edge / .022) * smoothstep((DURATION - 1 / RATE - edge) / .022)
    for name in score.stems:
        score.stems[name] *= master_gain * fade[:, None]
    return score.stems, dict(score.events)


def metrics(data: np.ndarray) -> dict[str, object]:
    adjacent = np.abs(np.diff(data, axis=0))
    spectrum = np.abs(np.fft.rfft(data.mean(axis=1))) ** 2
    frequencies = np.fft.rfftfreq(len(data), 1 / RATE)
    return {
        "frames": len(data), "seconds": len(data) / RATE,
        "peak": float(np.max(np.abs(data))), "rms": float(np.sqrt(np.mean(data ** 2))),
        "dc": data.mean(axis=0).tolist(), "first_sample": data[0].tolist(), "last_sample": data[-1].tolist(),
        "loop_boundary_delta": float(np.max(np.abs(data[0] - data[-1]))),
        "max_adjacent_delta": float(np.max(adjacent)), "adjacent_delta_p99": float(np.percentile(adjacent, 99)),
        "energy_fraction_above_6000_hz": float(spectrum[frequencies > 6000].sum() / max(1e-20, spectrum.sum())),
        "section_rms": [float(np.sqrt(np.mean(section ** 2))) for section in np.array_split(data, 4)],
    }


def write_wav(path: Path, data: np.ndarray) -> None:
    assert np.max(np.abs(data)) < 1
    with wave.open(str(path), "wb") as output:
        output.setnchannels(2)
        output.setsampwidth(2)
        output.setframerate(RATE)
        output.writeframes(np.rint(data * 32767).astype("<i2").tobytes())


def write_import(path: Path) -> None:
    source = "res://" + path.relative_to(ROOT).as_posix()
    digest = hashlib.md5(source.encode()).hexdigest()
    imported = f"res://.godot/imported/{path.name}-{digest}.oggvorbisstr"
    import_path = Path(str(path) + ".import")
    uid = ""
    if import_path.exists():
        uid = next((line for line in import_path.read_text(encoding="utf-8").splitlines() if line.startswith("uid=")), "")
    import_path.write_text(
        '[remap]\n\nimporter="oggvorbisstr"\ntype="AudioStreamOggVorbis"\n' + (uid + "\n" if uid else "")
        + f'path="{imported}"\n\n[deps]\n\nsource_file="{source}"\ndest_files=["{imported}"]\n\n[params]\n\n'
        + f'loop=true\nloop_offset=0\nbpm={BPM}.0\nbeat_count={BEATS}\nbar_beats=4\n', encoding="utf-8")


def main() -> None:
    ASSETS.mkdir(parents=True, exist_ok=True)
    DIAGNOSTICS.mkdir(parents=True, exist_ok=True)
    ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
    report = {
        "sample_rate": RATE, "channels": 2, "bpm": BPM, "beats": BEATS, "duration_seconds": DURATION,
        "frames_per_stem": FRAMES, "source": "Original offline additive-synthesis score; no external samples",
        "regenerate": "python tools/bake_music.py", "cues": {},
    }
    montage, total_bytes = [], 0
    for cue in CUES:
        print(f"Composing {cue.key}: {cue.title}", flush=True)
        stems, events = compose(cue)
        decoded_stems = {}
        cue_report = {"title": cue.title, "description": cue.description, "events": events, "stems": {}}
        for layer, data in stems.items():
            name = f"{cue.file_stem}_{layer}"
            wav_path, ogg_path = DIAGNOSTICS / f"{name}.wav", ASSETS / f"{name}.ogg"
            write_wav(wav_path, data)
            subprocess.run([ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-i", str(wav_path), "-map_metadata", "-1",
                            "-fflags", "+bitexact", "-flags:a", "+bitexact", "-c:a", "libvorbis", "-q:a", "2", str(ogg_path)], check=True)
            pcm = subprocess.run([ffmpeg, "-hide_banner", "-loglevel", "error", "-i", str(ogg_path),
                                  "-f", "f32le", "-acodec", "pcm_f32le", "-ar", str(RATE), "-ac", "2", "pipe:1"],
                                 check=True, stdout=subprocess.PIPE).stdout
            decoded = np.frombuffer(pcm, dtype="<f4").reshape(-1, 2).astype(np.float64)
            decoded_stems[layer] = decoded
            assert decoded.shape == data.shape, f"Vorbis changed {name}'s synchronization length"
            stats = metrics(decoded)
            assert stats["peak"] < .35, f"{name} exceeds reserved headroom"
            assert stats["loop_boundary_delta"] < .006, f"{name} has an audible loop discontinuity"
            assert np.max(np.abs(decoded[[0, -1]])) < .001, f"{name}'s decoded edges are not quiet"
            assert stats["max_adjacent_delta"] < .1, f"{name} has sharp waveform transitions"
            assert stats["energy_fraction_above_6000_hz"] < .0005, f"{name} has excessive high frequencies"
            write_import(ogg_path)
            size = ogg_path.stat().st_size
            total_bytes += size
            cue_report["stems"][layer] = {"file": ogg_path.name, "decoded": stats, "ogg_bytes": size,
                                          "sha256": hashlib.sha256(ogg_path.read_bytes()).hexdigest()}
        full_mix = decoded_stems["base"] + decoded_stems["energy"]
        combined = metrics(full_mix)
        assert combined["peak"] < .35, f"{cue.key}: full intensity exceeds reserved headroom"
        assert combined["loop_boundary_delta"] < .006
        assert combined["max_adjacent_delta"] < .1
        cue_report["full_intensity_decoded"] = combined
        report["cues"][cue.key] = cue_report
        write_wav(DIAGNOSTICS / f"{cue.key}_full_mix.wav", full_mix)
        write_wav(DIAGNOSTICS / f"{cue.key}_seam_review.wav", np.concatenate((full_mix[-RATE * 2:], full_mix[:RATE * 2])))
        excerpt = full_mix[RATE * 6:RATE * 16].copy()
        excerpt_time = np.arange(len(excerpt)) / RATE
        excerpt *= (smoothstep(excerpt_time / .35) * smoothstep((10 - 1 / RATE - excerpt_time) / .50))[:, None]
        montage.append(excerpt)
        print(f"  full peak={combined['peak']:.4f}; seam={combined['loop_boundary_delta']:.7f}; pair={sum(s['ogg_bytes'] for s in cue_report['stems'].values()):,} bytes", flush=True)
    assert total_bytes <= 4_000_000, f"Music payload too large: {total_bytes}"
    report["total_ogg_bytes"] = total_bytes
    sampler = DIAGNOSTICS / "FOLDLIGHT_五幕纸海_试听.wav"
